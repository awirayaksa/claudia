/**
 * File storage on the local disk (DATA_DIR/storage). With S3_BUCKET set,
 * S3Storage (./s3.ts) takes its place behind the same interface.
 */
import fs from 'node:fs';
import path from 'node:path';
import { Readable } from 'node:stream';

export interface Storage {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  stream(key: string): Readable;
  delete(key: string): Promise<void>;
  exists(key: string): Promise<boolean>;
}

const KEY_RE = /^[a-zA-Z0-9][a-zA-Z0-9/_.-]*$/;

export class LocalStorage implements Storage {
  constructor(private readonly root: string) {
    fs.mkdirSync(root, { recursive: true });
  }

  /** Keys are generated by the server; still, never let one leave the root. */
  private file(key: string): string {
    if (!KEY_RE.test(key) || key.includes('..')) throw new Error(`Invalid storage key: ${key}`);
    const p = path.resolve(this.root, key);
    if (!p.startsWith(path.resolve(this.root) + path.sep)) throw new Error(`Invalid storage key: ${key}`);
    return p;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const p = this.file(key);
    await fs.promises.mkdir(path.dirname(p), { recursive: true });
    // Write then rename, so readers never see half a file
    const tmp = `${p}.${process.pid}.${Date.now()}.tmp`;
    await fs.promises.writeFile(tmp, data);
    await fs.promises.rename(tmp, p);
  }

  get(key: string): Promise<Buffer> {
    return fs.promises.readFile(this.file(key));
  }

  stream(key: string): Readable {
    return fs.createReadStream(this.file(key));
  }

  async delete(key: string): Promise<void> {
    await fs.promises.rm(this.file(key), { force: true });
  }

  async exists(key: string): Promise<boolean> {
    try {
      await fs.promises.access(this.file(key));
      return true;
    } catch {
      return false;
    }
  }
}
